/** 转成 NativeWind `vars()` 需要的 `--c-*` 键名。 */
export function toVars(colors: Record<string, string>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(colors)) out[`--c-${k}`] = v;
  return out;
}
